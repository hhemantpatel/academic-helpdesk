"""
eval/plots.py - Figures (PDF + PNG), report/tables.tex and report/numbers.tex from evaluation results.

Every number in the report comes from results/*.csv. When a result does not exist yet the macro
expands to "TBD" and the table says "not run yet" - nothing is filled in by hand.
"""

import csv
import math
from pathlib import Path

import matplotlib
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

BASE_DIR = Path(__file__).resolve().parent.parent
FIGURES_DIR = BASE_DIR / "results" / "figures"
REPORT_DIR = BASE_DIR / "report"

# Validated categorical palette (fixed order, never cycled): blue, orange, aqua, yellow.
PALETTE = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100"]
INK, MUTED, GRID = "#1f1f1e", "#6b6a65", "#e4e3de"
CATEGORY_ORDER = ["policy", "schedule", "email", "out_of_scope", "uncovered"]
MODEL_MACRO = {"qwen3:8b": "Qwen", "llama3.1:8b": "Llama"}
SYSTEM_LABEL = {"multi": "Multi-agent", "single": "Single-agent"}


def _pct(x, na="TBD"):
    return na if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.1f}\\%"


def _num(x, fmt="{:.1f}"):
    return "TBD" if x is None or (isinstance(x, float) and math.isnan(x)) else fmt.format(x)


def _label(s):
    router = f", {s['router']} router" if s["system"] == "multi" else ""
    return f"{SYSTEM_LABEL.get(s['system'], s['system'])} ({s['model']}{router})"


def _style():
    plt.rcParams.update({
        "font.family": "serif", "font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK,
        "xtick.color": MUTED, "ytick.color": MUTED, "axes.grid": True, "grid.color": GRID,
        "grid.linewidth": 0.6, "axes.axisbelow": True, "axes.spines.top": False,
        "axes.spines.right": False, "legend.frameon": False, "savefig.dpi": 300,
        "savefig.bbox": "tight",
    })


def _save(fig, name):
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGURES_DIR / f"{name}.pdf")
    fig.savefig(FIGURES_DIR / f"{name}.png")
    plt.close(fig)


def plot_accuracy_by_category(scored: pd.DataFrame, summary: dict):
    configs = list(summary.values())
    cats = [c for c in CATEGORY_ORDER if c in set(scored["category"])]
    fig, ax = plt.subplots(figsize=(6.6, 2.8))
    width = 0.8 / len(configs)
    for i, s in enumerate(configs):
        g = scored[(scored.system == s["system"]) & (scored.model == s["model"]) & (scored.router == s["router"])]
        acc = g.groupby("category")["is_correct"].mean()
        xs = [k + (i - (len(configs) - 1) / 2) * width for k in range(len(cats))]
        ax.bar(xs, [acc.get(c, 0) for c in cats], width=width - 0.03, color=PALETTE[i % len(PALETTE)],
               label=_label(s), edgecolor="white", linewidth=1)
    ax.set_xticks(range(len(cats)), [c.replace("_", " ") for c in cats])
    ax.set_ylim(0, 1.0)
    ax.set_ylabel("Accuracy (fraction of runs)")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.15), ncol=2, fontsize=8)
    _save(fig, "accuracy_by_category")


def plot_latency_vs_accuracy(summary: dict):
    fig, ax = plt.subplots(figsize=(4.2, 3.0))
    for i, s in enumerate(summary.values()):
        ax.scatter(s["mean_latency"], s["accuracy"], s=60, color=PALETTE[i % len(PALETTE)],
                   edgecolor="white", linewidth=1.5, zorder=3, label=_label(s))
    ax.set_xlabel("Mean latency per question (s, CPU)")
    ax.set_ylabel("Accuracy")
    ax.set_ylim(0, 1.0)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.2), fontsize=7)
    _save(fig, "latency_vs_accuracy")


def corpus_stats():
    docs = sum(1 for _ in csv.DictReader(open(BASE_DIR / "ingest" / "manifest.csv", encoding="utf-8")))
    try:
        import chromadb
        from helpdesk.config import CHROMA_DIR, COLLECTION_NAME
        chunks = chromadb.PersistentClient(path=str(CHROMA_DIR)).get_collection(COLLECTION_NAME).count()
    except Exception:
        chunks = None
    return docs, chunks


def _table_rows(name: str):
    path = BASE_DIR / "data" / "tables" / name
    return sum(1 for _ in open(path, encoding="utf-8")) - 1 if path.exists() else "TBD"


def write_numbers(summary: dict, stability: pd.DataFrame, scored: pd.DataFrame):
    docs, chunks = corpus_stats()
    lines = ["% Generated by eval/plots.py from results/*.csv - do not edit by hand",
             f"\\newcommand{{\\numCorpusDocs}}{{{docs}}}",
             f"\\newcommand{{\\numCorpusChunks}}{{{chunks if chunks is not None else 'TBD'}}}",
             f"\\newcommand{{\\numCourses}}{{{_table_rows('courses.csv')}}}",
             f"\\newcommand{{\\numFaculty}}{{{_table_rows('faculty.csv')}}}",
             f"\\newcommand{{\\numSlotRows}}{{{_table_rows('slots.csv')}}}",
             f"\\newcommand{{\\numEvalQuestions}}{{{sum(1 for l in open(BASE_DIR / 'eval' / 'questions.jsonl') if l.strip())}}}",
             f"\\newcommand{{\\numTotalRuns}}{{{len(scored) if not scored.empty else 'TBD'}}}"]
    for system in ("multi", "single"):
        for model, mname in MODEL_MACRO.items():
            router = "llm" if system == "multi" else "none"
            s = summary.get(f"{system}|{model}|{router}", {})
            p = f"{system.capitalize()}{mname}"
            lines += [
                f"\\newcommand{{\\acc{p}}}{{{_pct(s.get('accuracy'))}}}",
                f"\\newcommand{{\\refF{p}}}{{{_num(s.get('refusal_f1'), '{:.2f}')}}}",
                f"\\newcommand{{\\falseRef{p}}}{{{_pct(s.get('false_refusal_rate'))}}}",
                f"\\newcommand{{\\citeRate{p}}}{{{_pct(s.get('citation_rate'))}}}",
                f"\\newcommand{{\\correctSrc{p}}}{{{_pct(s.get('correct_source_rate'))}}}",
                f"\\newcommand{{\\fabricated{p}}}{{{_pct(s.get('fabricated_rate'))}}}",
                f"\\newcommand{{\\routing{p}}}{{{_pct(s.get('routing_accuracy'), na='n/a')}}}",
                f"\\newcommand{{\\latency{p}}}{{{_num(s.get('mean_latency'))}}}",
            ]
    changed = int(stability.loc[stability["outcome_changed"], "question_id"].nunique()) if not stability.empty else None
    lines.append(f"\\newcommand{{\\numQuestionsChanged}}{{{changed if changed is not None else 'TBD'}}}")
    (REPORT_DIR / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _table(caption, label, colspec, header, rows, empty_msg="Not run yet."):
    ncol = len(colspec)
    body = rows or [f"\\multicolumn{{{ncol}}}{{c}}{{\\emph{{{empty_msg}}}}} \\\\"]
    return "\n".join([
        "\\begin{table}[h]", "\\centering", "\\small", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
        "\\resizebox{\\ifdim\\width>\\linewidth\\linewidth\\else\\width\\fi}{!}{%",
        f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\", "\\midrule", *body,
        "\\bottomrule", "\\end{tabular}}", "\\end{table}", ""])


def write_tables(scored, summary, stability, ablation_summary):
    out = ["% Generated by eval/plots.py from results/*.csv - do not edit by hand", ""]

    rows = [f"{SYSTEM_LABEL[s['system']]} & {s['model']} & {s['router']} & {s['runs']} & {_pct(s['accuracy'])} & "
            f"{_num(s['refusal_f1'], '{:.2f}')} & {_pct(s['false_refusal_rate'])} & {_pct(s['citation_rate'])} & "
            f"{_pct(s['correct_source_rate'])} & {_pct(s['fabricated_rate'])} & {_pct(s['routing_accuracy'], na='n/a')} & "
            f"{_num(s['mean_latency'])} \\\\" for s in summary.values()]
    out.append(_table(
        "Main results (all runs). Citation columns are over answered in-scope questions; routing is the first "
        "specialist the orchestrator delegated to.", "tab:main_results", "lllrrrrrrrrr",
        "System & Model & Router & Runs & Acc. & Ref.\\ F1 & False ref. & Cited & Correct src. & Fabric. & Routing & Lat.\\ (s)",
        rows))

    cat_rows = []
    for s in summary.values():
        g = scored[(scored.system == s["system"]) & (scored.model == s["model"]) & (scored.router == s["router"])]
        acc = g.groupby("category")["is_correct"].mean()
        cat_rows.append(f"{SYSTEM_LABEL[s['system']]} & {s['model']} & "
                        + " & ".join(_pct(acc.get(c, float('nan'))) for c in CATEGORY_ORDER) + " \\\\")
    out.append(_table("Accuracy by question category.", "tab:category", "llrrrrr",
                      "System & Model & Policy & Schedule & Email & Out of scope & Uncovered", cat_rows))

    st_rows = []
    if not stability.empty:
        for _, r in stability[stability["outcome_changed"]].sort_values(["question_id", "system", "model"]).iterrows():
            st_rows.append(f"{r['question_id']} & {r['category'].replace('_', ' ')} & {SYSTEM_LABEL[r['system']]} & "
                           f"{r['model']} & {r['n_correct']}/{r['runs']} & "
                           f"{'yes' if r['refusal_flipped'] else 'no'} & {r['avg_similarity']:.2f} \\\\")
    out.append(_table("Questions whose outcome changed across repeated runs (correct in only some runs, or "
                      "refused in only some runs).", "tab:stability", "lllllrr",
                      "Q & Category & System & Model & Correct & Refusal flip & Text sim.", st_rows,
                      empty_msg="No outcome changes observed." if not stability.empty else "Not run yet."))

    ab_rows = [f"{name.replace('_', ' ')} & {_pct(s['accuracy'])} & {_num(s['refusal_f1'], '{:.2f}')} & "
               f"{_pct(s['false_refusal_rate'])} & {_pct(s['correct_source_rate'])} & {_pct(s['fabricated_rate'])} \\\\"
               for name, s in ablation_summary.items()]
    out.append(_table("Ablation (multi-agent, one run per question): guardrails switched off and retrieval "
                      "threshold $\\tau$ changed (default 0.35).", "tab:ablation", "lrrrrr",
                      "Configuration & Acc. & Ref.\\ F1 & False ref. & Correct src. & Fabric.", ab_rows))
    (REPORT_DIR / "tables.tex").write_text("\n".join(out), encoding="utf-8")


_TEX_ESCAPES = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
                "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}"}


def _tex(text: str) -> str:
    """Escape LaTeX special characters in one pass (and drop markdown bold)."""
    import re
    text = str(text).replace("**", "")
    text = re.sub(r"[\\&%$#_{}~^]", lambda m: _TEX_ESCAPES[m.group(0)], text)
    for u, t in (("≥", r"$\geq$"), ("≤", r"$\leq$"), ("→", r"$\rightarrow$"), ("•", "-"), ("×", r"$\times$")):
        text = text.replace(u, t)
    return text


def write_questions():
    """Appendix: the full question set with expected behaviour."""
    import json
    rows = []
    for line in open(BASE_DIR / "eval" / "questions.jsonl", encoding="utf-8"):
        q = json.loads(line)
        rows.append(f"{q['id']} & {q['category'].replace('_', ' ')} & {_tex(q['question'])} & {_tex(q['gold_answer'])} "
                    f"& {_tex(', '.join(q['gold_sources']) or '--').replace(chr(92) + '_', chr(92) + '_' + chr(92) + 'allowbreak{}')} \\\\")
    body = "\n".join(rows)
    (REPORT_DIR / "questions.tex").write_text(
        "% Generated by eval/plots.py from eval/questions.jsonl\n"
        "\\begin{small}\n\\begin{longtable}{>{\\raggedright\\arraybackslash}p{0.6cm}>{\\raggedright\\arraybackslash}p{1.4cm}>{\\raggedright\\arraybackslash}p{4.3cm}>{\\raggedright\\arraybackslash}p{5.6cm}>{\\raggedright\\arraybackslash}p{2.3cm}}\n\\toprule\n"
        "ID & Category & Question & Expected answer / behaviour & Gold sources \\\\\n\\midrule\n\\endhead\n"
        f"{body}\n\\bottomrule\n\\end{{longtable}}\n\\end{{small}}\n", encoding="utf-8")


CASE_QUESTIONS = ["Q01", "Q09", "Q10", "Q17", "Q18", "Q23"]


def write_case_studies(runs: pd.DataFrame):
    """Real transcripts (first multi-agent run of a few questions), copied verbatim from results/runs.csv."""
    import json
    parts = ["% Generated by eval/plots.py from results/runs.csv - verbatim system output"]
    if runs is None or runs.empty:
        parts.append("\\emph{Not run yet.}")
    else:
        qs = {json.loads(l)["id"]: json.loads(l)["question"] for l in open(BASE_DIR / "eval" / "questions.jsonl")}
        multi = runs[(runs["system"] == "multi") & (runs["run_idx"].astype(str) == "1")]
        for qid in CASE_QUESTIONS:
            r = multi[multi["question_id"] == qid].head(1)
            if r.empty:
                continue
            r = r.iloc[0]
            route = " $\\rightarrow$ ".join(_tex(a) for a in json.loads(r["route"] or "[]"))
            tools = ", ".join(_tex(t[0]) for t in json.loads(r["tools_called"] or "[]")) or "none"
            parts.append(
                f"\\paragraph{{{qid} ({_tex(r['model'])}).}} \\emph{{{_tex(qs[qid])}}}\\\\\n"
                f"\\textbf{{Route:}} {route}\\quad \\textbf{{Tools:}} {tools}\\quad "
                f"\\textbf{{Latency:}} {float(r['latency']):.0f}\\,s\\\\\n"
                f"\\textbf{{Answer:}} {_tex(r['answer'])}\n")
    (REPORT_DIR / "case_studies.tex").write_text("\n".join(parts) + "\n", encoding="utf-8")


def generate_outputs(scored: pd.DataFrame, summary: dict, stability: pd.DataFrame, ablation_summary: dict,
                     runs: pd.DataFrame = None):
    _style()
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    if summary:
        plot_accuracy_by_category(scored, summary)
        plot_latency_vs_accuracy(summary)
    write_numbers(summary, stability, scored)
    write_tables(scored, summary, stability, ablation_summary)
    write_questions()
    write_case_studies(runs)
    print(f"Wrote figures to {FIGURES_DIR} and report/numbers.tex, report/tables.tex")


